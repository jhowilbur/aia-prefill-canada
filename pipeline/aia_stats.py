"""Recompute every number in docs/data-notes.md from data/SOURCES.csv, data/interim/aia/*.json and
catalog/requirements.jsonl, then (re)write docs/data-notes.md and reports/aia_question_coverage.csv.
Run: python3 -I pipeline/aia_stats.py
"""
import collections, csv, glob, json, os, statistics, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "pipeline"))
import aia_score  # noqa: E402

recs = [json.load(open(f, encoding="utf-8")) for f in sorted(glob.glob(os.path.join(ROOT, "data/interim/aia/*.json")))]
cat = [json.loads(l) for l in open(os.path.join(ROOT, "catalog/requirements.jsonl"), encoding="utf-8")]
src = list(csv.DictReader(open(os.path.join(ROOT, "data/SOURCES.csv"), encoding="utf-8")))
survey = aia_score.load_survey()

N = len(recs)
js = [r for r in recs if r["answers_source"] == "json"]
pdf_only = [r for r in recs if r["answers_source"] == "pdf_only"]


def empty(v):
    return v is None or v == "" or v == [] or v == {}


def n_chars(s):
    return len(s or "")


ft = {r["id"]: n_chars("\n".join(r["free_text_answers"].values())) for r in recs}
indep = {r["id"]: n_chars(r["ckan_notes"]) + n_chars(r["supporting_text"]) for r in recs}
desc = {r["id"]: n_chars(r["free_text_answers"].get("projectDetailsDescription")) for r in recs}
supp_n = sum(1 for r in recs if r["supporting_docs"])
notes_n = sum(1 for r in recs if r["ckan_notes"])


def dist(vals):
    v = sorted(vals)
    return f"min {v[0]:,} / median {int(statistics.median(v)):,} / max {v[-1]:,}"


def ge(d, ids, t):
    return sum(1 for i in ids if d[i] >= t)


js_ids = [r["id"] for r in js]
all_ids = [r["id"] for r in recs]

lang = collections.Counter(r["language"] for r in js)
has_fr_tr = sum(1 for r in js if r["free_text_fr"])
alt = sum(1 for r in js if r["alternate_jsons"])
src_lang = collections.Counter(row["language"] or "none" for row in src)
fmt = collections.Counter(row["format"] for row in src)
lic = collections.Counter(row["licence"] for row in src)
total_bytes = sum(int(row["bytes"] or 0) for row in src)
errors = sum(1 for row in src if row["status"] != "ok")
depts = collections.Counter(r["department"] for r in recs)
years = collections.Counter(r["date"][:4] for r in recs)
levels = collections.Counter(r["impact_level"] for r in recs)
scored = [r for r in recs if r["raw_score"] is not None]
versions = collections.Counter(r["tool_version"] for r in js)

# score cross-check with the CURRENT survey scorer
match = mism = 0
byver = collections.defaultdict(lambda: [0, 0])
for r in js:
    if r["raw_score"] is None:
        continue
    data = dict(r["answers"]); data.update(r["answers_unmapped"])
    s = aia_score.score(survey, data)
    if s["raw_impact_score"] == r["raw_score"]:
        match += 1; byver[r["tool_version"]][0] += 1
    else:
        mism += 1; byver[r["tool_version"]][1] += 1

# per-question coverage over JSON AIAs
unm = collections.Counter(k for r in js for k in r["answers_unmapped"])
rows = []
for q in cat:
    n = sum(1 for r in js if not empty(r["answers"].get(q["id"])))
    rows.append({"id": q["id"], "page": q["page"], "kind": q["kind"], "question_type": q["question_type"],
                 "answered": n, "of": len(js), "pct": round(100 * n / len(js), 1) if js else 0})
os.makedirs(os.path.join(ROOT, "reports"), exist_ok=True)
with open(os.path.join(ROOT, "reports/aia_question_coverage.csv"), "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
bands = collections.Counter()
for x in rows:
    p = x["pct"]
    bands["100%" if p == 100 else ">=90%" if p >= 90 else "50-89%" if p >= 50 else "1-49%" if p > 0 else "0%"] += 1
bykind = collections.defaultdict(list)
for x in rows:
    bykind[x["kind"]].append(x["pct"])
bypage = collections.OrderedDict()
for x in rows:
    bypage.setdefault(x["page"], []).append(x)
per_aia = [sum(1 for q in cat if not empty(r["answers"].get(q["id"]))) for r in js]

L = []
a = L.append
a("# Published AIAs: data notes")
a("")
a("Generated by `pipeline/aia_stats.py` from `data/SOURCES.csv`, `data/interim/aia/*.json` and")
a("`catalog/requirements.jsonl`. Every number below is computed by that script; rerun it after any change.")
a("Source search: CKAN `package_search q=\"Algorithmic Impact\"` on open.canada.ca (see `pipeline/fetch_aia.py`);")
a("the blank AIA tool dataset (TBS) and the GC AI Register are excluded because they are not system AIAs.")
a("")
a("## Counts")
a(f"- Published AIA datasets: **{N}** from **{len(depts)}** departments/agencies; files downloaded: **{len(src)}** "
  f"({total_bytes/1e6:.1f} MB, {errors} download errors).")
a(f"- File formats: " + ", ".join(f"{k} {v}" for k, v in fmt.most_common()) + ".")
a(f"- Licence on every file: " + ", ".join(f"{k} ({v})" for k, v in lic.items()) + ".")
a(f"- Publication year (dataset metadata): " + ", ".join(f"{k}: {v}" for k, v in sorted(years.items())) + ".")
a(f"- Departments: " + "; ".join(f"{k} {v}" for k, v in depts.most_common()) + ".")
a(f"- **Machine-readable answers (tool JSON export): {len(js)} of {N}.** The other {len(pdf_only)} "
  f"({', '.join(r['id'][:8] for r in pdf_only)}) publish the AIA only as PDF/DOCX; their answers are NOT parsed "
  "into question ids yet (answers = {}), only their score and level are read.")
a(f"- Impact level found for {sum(1 for r in recs if r['impact_level'] is not None)} of {N}; distribution: "
  + ", ".join(f"level {k}: {v}" for k, v in sorted(levels.items(), key=lambda kv: (kv[0] is None, kv[0] or 0))) + ".")
a(f"- Raw impact score found for {len(scored)} of {N} ({dist([r['raw_score'] for r in scored])}).")
a(f"- Tool versions of the JSON exports: " + ", ".join(f"{k} {v}" for k, v in sorted(versions.items(), key=lambda kv: str(kv[0]))) + ".")
a(f"- Raw score recomputed from the JSON answers with the CURRENT survey scorer (`pipeline/aia_score.py`) equals "
  f"the published raw score for **{match}** of {match + mism} AIAs that have both. By tool version (match/mismatch): "
  + ", ".join(f"{k} {v[0]}/{v[1]}" for k, v in sorted(byver.items(), key=lambda kv: str(kv[0])))
  + ". The pattern points to survey drift (older versions had other questions/weights); a PDF score from another "
  "assessment version than the JSON is a second possible cause. Use the published score/level as truth, not a recomputation.")
a("")
a("## Free text describing the system (the model's input)")
a("Three different kinds of text exist; they are NOT equivalent for the test:")
a(f"1. **Free-text answers inside the AIA** (comment/text fields, admin fields like respondent excluded): "
  f"present in {sum(1 for i in js_ids if ft[i] > 0)} of {len(js)} JSON AIAs; length {dist([ft[i] for i in js_ids])} chars; "
  f">= 2,000 chars in {ge(ft, js_ids, 2000)}, >= 5,000 in {ge(ft, js_ids, 5000)}. The project description field alone "
  f"(projectDetailsDescription) is filled in {sum(1 for i in js_ids if desc[i] > 0)} of {len(js)} ({dist([desc[i] for i in js_ids])} chars). "
  "**Leakage warning:** these were written by the same team in the same form, often justifying the selected option "
  "(for example impact8 explains impact7). Using them as input measures \"read the AIA's own narrative\", not "
  "\"read system documentation\".")
a(f"2. **Independent text** = open.canada.ca dataset description + supporting documents that are not the AIA "
  f"(GBA+ summaries, peer-review summaries, model descriptions): dataset description in {notes_n} of {N}; supporting "
  f"documents in {supp_n} of {N}. Combined length {dist([indep[i] for i in all_ids])} chars; >= 2,000 chars in "
  f"{ge(indep, all_ids, 2000)} of {N}, >= 10,000 in {ge(indep, all_ids, 10000)}; among the {len(js)} JSON AIAs: "
  f">= 2,000 chars in {ge(indep, js_ids, 2000)}, >= 10,000 in {ge(indep, js_ids, 10000)}. "
  "These raw figures are NOT the model input: they include the f77faef4 AIA-annex DOCX (143,602 chars, AIA text) "
  "and peer-review files, whose mere presence reveals level II (audit round 2, M-A). The leakage-free input and its "
  "counts are in `docs/inputs.md`.")
a("3. **The AIA rendered as PDF**: contains the questions AND the answers; never use it as input. Kept only for score/level "
  "(`aia_pdf_text_files`).")
a("")
a("`description_text` in each interim file is 1 + 2 concatenated (as specified); the split fields "
  "`free_text_answers`, `ckan_notes`, `supporting_text` keep the parts apart. **None of them is leakage-free as is:** "
  "`supporting_text` contains AIA annexes and peer-review files. The only model input is `data/interim/inputs` "
  "(built by `pipeline/build_inputs.py`, rule and counts in `docs/inputs.md`).")
a("")
a("## Language")
a(f"- Language of the primary JSON's free text: " + ", ".join(f"{k} {v}" for k, v in lang.most_common()) + f" (of {len(js)}).")
a(f"- JSON AIAs that also carry a French translation of the free text (translationsOnResult): {has_fr_tr}; "
  f"datasets with more than one JSON (EN/FR pair or several versions; the parser keeps one, preferring English then the newest tool version): {alt}.")
a(f"- File language tags in SOURCES.csv: " + ", ".join(f"{k} {v}" for k, v in src_lang.most_common()) + ".")
a("")
a("## Answer coverage per question (JSON AIAs only)")
a(f"Question ids from `catalog/requirements.jsonl` ({len(cat)} ids). Answered = non-empty value in the published JSON.")
a(f"- Answered questions per AIA: {dist(per_aia)} of {len(cat)} (many questions are conditional, so empty is often correct).")
a(f"- Questions by coverage band: " + ", ".join(f"{k}: {bands[k]}" for k in ["100%", ">=90%", "50-89%", "1-49%", "0%"]) + ".")
for k, v in sorted(bykind.items()):
    a(f"- {k}: {len(v)} questions, mean coverage {statistics.mean(v):.1f}%, never answered {sum(1 for x in v if x == 0)}.")
a("")
a("| Page | questions | mean coverage | never answered |")
a("|---|---|---|---|")
for pg, xs in bypage.items():
    a(f"| {pg} | {len(xs)} | {statistics.mean(x['pct'] for x in xs):.1f}% | {sum(1 for x in xs if x['answered'] == 0)} |")
a("")
a("Full per-question table: `reports/aia_question_coverage.csv`.")
a("")
a(f"**Unmapped keys** (in published JSON, absent from the current survey; kept in `answers_unmapped`): "
  + ", ".join(f"`{k}` ({v})" for k, v in unm.most_common()) + ".")
a("")
a("## Limits")
a(f"- Small sample: {len(js)} AIAs with question-level labels (+{len(pdf_only)} PDF-only). Impact levels 3 and 4 "
  f"{'are absent' if not any((k or 0) >= 3 for k in levels) else 'are rare'}: no ground truth for high-impact systems.")
a("- Survey drift: the exports span several tool versions; some ids were renamed or dropped, so per-question labels "
  "for older AIAs are partial against the current questionnaire, and old answer weights may differ.")
a("- Selection bias: only systems departments chose to publish (mostly IRCC/ESDC triage tools).")
a("- No real system documentation (design docs, model cards) is published; the independent text is short summaries.")
a("- PDF text comes from `pdftotext -layout`; tables can lose order. DOCX text is raw XML text.")
a("- Score/level are read from the AIA PDF; when a dataset has several assessment versions the PDF may not match the chosen JSON.")
open(os.path.join(ROOT, "docs/data-notes.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(L))
