"""Leakage probe: can one simple feature of the model input separate impact level I from II?

For the C-narr and C-ext CV pools (eval-plan.md v1.1: JSON AIAs minus the lock-box = the most
recent 7 by dataset date; C-ext = CV AIAs with >= 2,000 chars of `documents`), it computes the
ROC AUC of each single feature against the published level (II = positive). Separation is
reported as max(AUC, 1 - AUC); > 0.9 is flagged. A clean input should flag nothing.

Features are computed on exactly what the model reads (C-narr: class-(a) fields + documents;
C-ext: documents only). One reference row ("raw corpus: peer-review file published") shows the
confound the input build removes; it is not a model-input feature and is never flagged.

    python3 -I pipeline/leak_probe.py      # writes reports/leak_probe.md
"""
from __future__ import annotations

import json
import math
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build_inputs as B  # noqa: E402

ROOT = HERE.parent
REPORT = ROOT / "reports" / "leak_probe.md"
LOCKBOX_FRAC, LOCKBOX_MIN, MIN_CHARS, FLAG = 0.20, 5, 2000, 0.9
GBA = re.compile(r"gba|acs-plus|analyse-comparative|lacs-plus|sexes-plus", re.I)
KEYWORDS = {
    "keyword 'peer review' / 'par les pairs'": re.compile(r"peer[\s-]*review|par\s+les\s+pairs", re.I),
    "keyword 'level'": re.compile(r"\blevels?\b", re.I),
    "keyword 'niveau'": re.compile(r"\bniveaux?\b", re.I),
    "keyword 'impact level' / 'niveau d'incidence'": re.compile(r"impact\s+level|niveau\s+d\W{0,2}\s*incidence", re.I),
}


def auc(scores: list[float], labels: list[int]) -> float:
    """Mann-Whitney AUC with ties counted 1/2; positives = label 1."""
    pos = [s for s, y in zip(scores, labels) if y == 1]
    neg = [s for s, y in zip(scores, labels) if y == 0]
    if not pos or not neg:
        return float("nan")
    wins = sum((p > n) + 0.5 * (p == n) for p in pos for n in neg)
    return wins / (len(pos) * len(neg))


def load():
    aias = {json.loads(p.read_text(encoding="utf-8"))["id"]: json.loads(p.read_text(encoding="utf-8"))
            for p in (ROOT / "data/interim/aia").glob("*.json")}
    inputs = {json.loads(p.read_text(encoding="utf-8"))["id"]: json.loads(p.read_text(encoding="utf-8"))
              for p in (ROOT / "data/interim/inputs").glob("*.json")}
    return aias, inputs


def pools(aias, inputs):
    js = [a for a in aias.values() if a["answers_source"] == "json"]
    k = max(LOCKBOX_MIN, math.ceil(LOCKBOX_FRAC * len(js)))
    lock = {a["id"] for a in sorted(js, key=lambda a: (a["date"], a["id"][:8]))[-k:]}
    cv = [a["id"] for a in js if a["id"] not in lock]
    cext = [i for i in cv if inputs[i]["chars_documents"] >= MIN_CHARS]
    return {"C-narr": cv, "C-ext": cext}


def features(aid, aia, inp, cond):
    docs = inp["documents"]
    texts = [d["text"] for d in docs] + (list(inp["aia_fields_a"].values()) if cond == "C-narr" else [])
    text = "\n".join(texts)
    sup = [d for d in docs if d["source"] == "supporting_doc"]
    f = {
        "supporting document present": float(bool(sup)),
        "number of supporting documents": float(len(sup)),
        "GBA+ document present": float(any(GBA.search(Path(d["file"]).name) for d in sup)),
        "peer-review document in input": float(any(B.is_level_revealing(d["file"], d["text"]) for d in sup)),
        "input length (chars)": float(len(text)),
    }
    for name, rx in KEYWORDS.items():
        f[name] = float(bool(rx.search(text)))
    ref = float(any(B.LEVEL_REVEALING_DOC.search(Path(sd["file"]).name) for sd in aia["supporting_docs"]))
    return f, ref


def main() -> dict:
    aias, inputs = load()
    out, lines = {}, ["# Leakage probe: single-feature separation of impact level I vs II", "",
                      "Generated by `python3 -I pipeline/leak_probe.py` from `data/interim/inputs` (model input) and",
                      "`data/interim/aia` (published level). AUC with level II as positive; separation = max(AUC, 1 − AUC);",
                      f"**flag if separation > {FLAG}**. Binary features: AUC = (TPR + TNR) / 2 of the rule \"present ⇒ II\".",
                      "Small pools: one AIA moves a binary AUC by up to 1/(2·n_level) — read with the counts.", ""]
    for cond, ids in pools(aias, inputs).items():
        labels = [1 if aias[i]["impact_level"] == 2 else 0 for i in ids]
        rows, refs = {}, []
        for i in ids:
            f, ref = features(i, aias[i], inputs[i], cond)
            refs.append(ref)
            for k, v in f.items():
                rows.setdefault(k, []).append(v)
        n2, n1 = sum(labels), len(labels) - sum(labels)
        lines += [f"## {cond} CV pool: {len(ids)} AIAs (level I: {n1}, level II: {n2})", "",
                  "| feature | AUC | separation | present in I / II | flag |", "|---|---|---|---|---|"]
        res = {}
        for k, vals in rows.items():
            a = auc(vals, labels)
            sep = max(a, 1 - a) if a == a else float("nan")
            binary = set(vals) <= {0.0, 1.0}
            pres = (f"{int(sum(v for v, y in zip(vals, labels) if y == 0))}/{n1} / "
                    f"{int(sum(v for v, y in zip(vals, labels) if y == 1))}/{n2}") if binary else "—"
            flag = sep > FLAG
            res[k] = {"auc": a, "sep": sep, "flag": flag}
            lines.append(f"| {k} | {a:.3f} | {sep:.3f} | {pres} | {'**FLAG**' if flag else ''} |")
        a = auc(refs, labels)
        lines.append(f"| *reference, not input: peer-review file published in raw corpus* | {a:.3f} | "
                     f"{max(a, 1 - a):.3f} | {int(sum(r for r, y in zip(refs, labels) if y == 0))}/{n1} / "
                     f"{int(sum(r for r, y in zip(refs, labels) if y == 1))}/{n2} | (removed by build) |")
        lines.append("")
        out[cond] = {"n": len(ids), "n1": n1, "n2": n2, "features": res, "reference_auc": a}
    flagged = [(c, k) for c, r in out.items() for k, v in r["features"].items() if v["flag"]]
    lines += ["## Verdict", "",
              ("No single input feature separates the levels above the flag." if not flagged else
               "Flagged: " + "; ".join(f"{c}: {k}" for c, k in flagged) + ". Investigate before any result."), ""]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    out["flagged"] = flagged
    return out


if __name__ == "__main__":
    main()
